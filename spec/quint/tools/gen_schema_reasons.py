#!/usr/bin/env python3
"""Generate schema.qnt: per-command failure reasons and directions from tachyon/schema/*/*/*.json.

Run from repo root: python3 spec/quint/tools/gen_schema_reasons.py > spec/quint/schema.qnt
"""
import glob, json, os, sys

root = os.path.join(os.path.dirname(__file__), "..", "..", "..", "schema")

def reasons_of(d):
    out = set()
    def walk(x):
        if isinstance(x, dict):
            if x.get("properties", {}).get("status", {}).get("const") == "failed":
                r = x["properties"].get("reason", {})
                out.update(r.get("enum", []) or ([r["const"]] if "const" in r else []))
            for v in x.values():
                walk(v)
        elif isinstance(x, list):
            for v in x:
                walk(v)
    walk(d)
    return out

cmds = {}
for f in sorted(glob.glob(os.path.join(root, "*", "*", "*.json"))):
    rel = os.path.relpath(f, root)[:-5]
    g, c, kind = rel.split(os.sep)
    d = json.load(open(f))
    e = cmds.setdefault(f"{g}/{c}", {"kinds": set(), "reasons": set(), "dir": None})
    e["kinds"].add(kind)
    if kind in ("request", "event"):
        t = d.get("tachyon", {})
        e["dir"] = f'{t.get("source")}->{t.get("target")}'
    if kind == "response":
        e["reasons"] |= reasons_of(d)

def qset(xs):
    return "Set(" + ", ".join(f'"{x}"' for x in sorted(xs)) + ")"

print("// GENERATED by tools/gen_schema_reasons.py from tachyon/schema. Do not edit.")
print("module schema {")
print("  // Failure reasons each response schema allows (includes the 4 generic ones).")
print("  pure val REASONS: str -> Set[str] = Map(")
rows = [f'    "{k}" -> {qset(v["reasons"])}' for k, v in cmds.items() if "response" in v["kinds"]]
print(",\n".join(rows))
print("  )")
print("  // Request commands (have a response) and event commands (no response).")
print("  pure val REQUESTS: Set[str] = " + qset(k for k, v in cmds.items() if "request" in v["kinds"]))
print("  pure val EVENTS: Set[str] = " + qset(k for k, v in cmds.items() if "event" in v["kinds"]))
print("  // Direction source->target as in the schema's tachyon block.")
print("  pure val DIRECTION: str -> str = Map(")
print(",\n".join(f'    "{k}" -> "{v["dir"]}"' for k, v in cmds.items()))
print("  )")
print("  pure def reasonAllowed(cmd: str, r: str): bool = REASONS.keys().contains(cmd) and REASONS.get(cmd).contains(r)")
print("}")
